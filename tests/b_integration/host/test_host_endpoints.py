def test_slides_can_load_its_themes(live: LiveHost):
    """themes.js and every theme.bin it names.

    Both are generated by payload.sh: sdkjs ships the designs as .pptx and
    nothing else, and the editor asks for themeN/theme.bin by index into
    g_defaultThemes. A missing themes.js is a 404 and an empty theme gallery.
    """
    themes = live.get_static("/sdkjs/slide/themes//themes.js").decode()
    # Past the window["AscCommon"]["g_defaultThemes"] brackets to the array.
    tail = themes.split("g_defaultThemes")[-1]
    names = json.loads(tail[tail.index("[") : tail.rindex("]") + 1])
    assert names, "themes.js names no themes"

    for index in range(1, len(names) + 1):
        binary = live.get_static(f"/sdkjs/slide/themes/theme{index}/theme.bin")
        assert binary, f"theme{index} ({names[index - 1]}) has an empty theme.bin"


