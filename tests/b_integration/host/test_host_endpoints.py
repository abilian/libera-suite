def test_the_start_page_reaches_the_host_one_way_only(live: LiveHost):
    """One helper, which throws on a bad status, so nothing can forget to check.

    fetch resolves for 404 and 500; only a network error rejects it. A second
    call site that used fetch directly would be a caller that sees a failure
    as success, which is how the start window came to sit there disabled.
    """
    page = live.get("start").decode()
    assert page.count("fetch(") == 1, "something reaches the host without host()"
    assert "if (!response.ok)" in page, "host() stopped checking the status"


def test_the_start_page_uses_the_editors_own_palette(live: LiveHost):
    """Same token names, same values, taken from the payload's own CSS.

    The start window sits beside the editor, so "aligned" has to mean the
    actual colours and not colours that looked close once. If upstream retunes
    its theme, this is what notices.
    """
    import re

    editor_css = (
        live.host.payload / "web-apps" / "apps" / "documenteditor" / "main" / "app.css"
    ).read_text(errors="replace")
    # The :root block is the default theme -- what the editor renders with
    # until someone changes it.
    root = max(
        (
            m.group(2)
            for m in re.finditer(
                r"\{([^{}]*?)(--background-normal:[^{}]*)\}", editor_css
            )
        ),
        key=len,
    )
    theirs = dict(re.findall(r"(--[a-z-]+):\s*([^;]+)", root))

    page = live.get("start").decode()
    ours = dict(re.findall(r"(--[a-z-]+):\s*([^;]+);", page))

    checked = 0
    for token, value in ours.items():
        if token in theirs:
            assert value.strip() == theirs[token].strip(), (
                f"{token} is {value.strip()} here and {theirs[token].strip()} in the editor"
            )
            checked += 1
    assert checked >= 10, (
        f"only {checked} tokens compared; the page stopped using theirs"
    )


def test_every_new_button_has_a_tile_to_draw(live: LiveHost):
    """An editor that can create has to have a mark, or New draws a blank.

    The page builds each button's icon as `<use href="#tile-{name}">` from the
    name the host handed it. A reference to a symbol that is not there renders
    nothing at all -- no error, no console message, an empty 28px square -- so
    a fifth editor, or a renamed one, would go out looking finished. The brand
    has a tile for three of the four and Diagrams creates nothing, which is the
    only reason this passes today.
    """
    page = live.get("start").decode()
    creates = [app["name"] for app in live.json("apps") if app["creates"]]
    assert creates, "no editor can create anything; the page has nothing to show"
    for name in creates:
        assert f'id="tile-{name}"' in page, f"New offers {name} and has no tile for it"


